def _reg_escape(value: str) -> str:
    """.reg 的**值**里反斜杠要双写、引号要前置反斜杠：`C:\\x` 写成 `C:\\\\x`，`"y"` 写成 `\\"y\\"`。
    先双写反斜杠再转义引号——反过来的话引号那条会把自己刚插进去的反斜杠再逃一遍。
    键名那一行**不走这里**：regedit 的键路径本来就是单反斜杠。"""
    return value.replace(BS, BS + BS).replace('"', BS + '"')


def media_exts(src: str | None = None) -> list[str]:
    """播放器能打开的扩展名名单——**从 app/engine/player.py 的 MEDIA_EXTS 用 AST 取**。

    为什么不走 import：那条路会拉起 PyQt5 与内核模块，一个"生成模板"的脚本不该付这个代价，
    也不该因为某个 GUI 依赖没装就生成不出来。为什么不手抄：手抄的名单会在 app 加格式那天
    悄悄落后，而落在注册表里的落后是看不见的（右键某个新格式时只会说"没有这个播放器"）。
    """
    path = src or BS.join((ROOT, "app", "engine", "player.py"))
    tree = ast.parse(open(path, encoding="utf-8").read(), filename=path)
    node = next((n for n in tree.body
                 if isinstance(n, ast.Assign)
                 and any(getattr(t, "id", "") == "MEDIA_EXTS" for t in n.targets)), None)
    if node is None:
        raise LookupError(f"{path} 里找不到 MEDIA_EXTS 的赋值：名单不许手抄，取不到就停")
    if not isinstance(node.value, (ast.Set, ast.Tuple, ast.List)):
        raise LookupError("MEDIA_EXTS 不是集合/列表字面量（换成推导式就得改这里的取法）")
    items = [c.value for c in node.value.elts if isinstance(c, ast.Constant)]
    if len(items) != len(node.value.elts):
        raise LookupError("MEDIA_EXTS 里混进了非字面量成员，取不全 ⇒ 不敢拿去生成")
    out = sorted({i.lower() if i.startswith(".") else "." + i.lower() for i in items})
    if len(out) < 20 or any(not s.startswith(".") or len(s) > 8 for s in out):
        raise LookupError(f"MEDIA_EXTS 取出来不像话（{len(out)} 条）：先修 player.py 再生成")
    return out


def cs_lit(text: str) -> str:
    """C# 字符串字面量：反斜杠双写、非 ASCII 一律走 \\uXXXX——整份 .cs 因此是纯 ASCII，
    csc 用哪种代码页读它都不影响结果（本机控制台是 936，带中文的源文件编码最容易出事）。"""
    out = []
    for ch in text:
        if ch == BS:
            out.append(BS + BS)
        elif ch == '"':
            out.append(BS + '"')
        elif ord(ch) < 128:
            out.append(ch)
        else:
            out.append("\\u%04x" % ord(ch))
    return '"' + "".join(out) + '"'


