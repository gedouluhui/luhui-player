def lint_cs(text: str) -> list[str]:
    """启动器源码的形状检查——它编不成 exe 就没法注册，所以这几条是真闸门。"""
    problems = []
    try:
        text.encode("ascii")
    except UnicodeEncodeError as exc:
        problems.append(f".cs 里有非 ASCII（第 {exc.start} 字节起）：中文必须走 \\uXXXX，"
                        "否则 csc 按代码页读入会变问号")
    for tok in (f"[assembly: AssemblyTitle({cs_lit(APP_TITLE)})",
                'Pick("LUHUI_LAUNCHER_PROBE",',
                "UseShellExecute = false",
                "ProcessStartInfo", "psi.WorkingDirectory = root"):
        if tok not in text:
            problems.append(f"缺这一句：{tok[:48]}")
    if "// Generated by packaging" not in text:
        problems.append("没写「由脚本生成」这行：手改的 .cs 会被下一次生成悄悄覆盖")
    # 特性行单独查：这几行的字面量是本函数**拼**出来的，多打一个引号就成了 `"....")]`，
    # csc 报的是"常量中有换行符"（CS1010）——那条错误信息指不到"多了个引号"，所以在这里点名。
    # 判据用**每行引号个数的奇偶**而不是"有没有相邻两个引号"：Quote() 里的 `"\\\""` 合法地
    # 含有相邻引号，按串查会误伤（这条是当场试出来的）。
    for line in text.splitlines():
        if line.startswith("[assembly:") and line.count('"') % 2:
            problems.append(f"程序集特性行里引号不成对：{line[:72]}")
        if line.startswith("[assembly:") and not line.endswith(")]"):
            problems.append(f"程序集特性行没收在 `)]` 上：{line[:72]}")
    if text.count("{") != text.count("}"):
        problems.append("花括号不成对")
    return problems


def file_description(path: str) -> str | None:
    """取 exe 的 FileDescription——「打开方式」列表里那行名字就是它（本机实测）。"""
    v = ctypes.windll.version
    v.GetFileVersionInfoSizeW.argtypes = [ctypes.c_wchar_p, ctypes.POINTER(ctypes.c_uint)]
    v.GetFileVersionInfoW.argtypes = [ctypes.c_wchar_p, ctypes.c_uint, ctypes.c_uint,
                                      ctypes.c_void_p]
    v.VerQueryValueW.argtypes = [ctypes.c_void_p, ctypes.c_wchar_p,
                                 ctypes.POINTER(ctypes.c_void_p), ctypes.POINTER(ctypes.c_uint)]
    dummy = ctypes.c_uint(0)
    size = v.GetFileVersionInfoSizeW(path, ctypes.byref(dummy))
    if not size or not os.path.exists(path):
        return None
    buf = ctypes.create_string_buffer(size)
    if not v.GetFileVersionInfoW(path, 0, size, buf):
        return None

    def query_bytes(sub):
        p, ln = ctypes.c_void_p(), ctypes.c_uint()
        if not v.VerQueryValueW(buf, BS + sub, ctypes.byref(p), ctypes.byref(ln)):
            return None
        return ctypes.string_at(p, ln.value)

    def query_w(sub):
        """取一个文本值。坑在这儿的单位：**VS_VERSIONINFO 里文本节点的 wValueLength 数的是
        宽字符个数（含结尾 NUL），不是字节数**，而 VerQueryValueW 把这个数原样回给你。
        本机实测：FileDescription＝"格斗芦荟播放器"（7 字）时它回 8，按 8 **字节**读只剩 4 个字
        ——"格斗芦荟"，看着像资源被截了，其实是量具自己咬掉半截（.NET 的 VersionInfo 读出来是全的，
        两份实现一对才暴露）。所以按 len 个**宽字符**读，再在第一个 NUL 处切，两种口径都不怕。"""
        p, ln = ctypes.c_void_p(), ctypes.c_uint()
        if not v.VerQueryValueW(buf, BS + sub, ctypes.byref(p), ctypes.byref(ln)) or not ln.value:
            return None
        try:
            got = ctypes.wstring_at(p, ln.value)
        except Exception:
            got = ctypes.string_at(p, ln.value * 2).decode("utf-16-le", "replace")
        return got.split("\x00")[0] or None

    # Translation 那节是**字节对**（语言 2 字节小端 + 代码页 2 字节小端），类型是二进制，
    # 所以它的 len 就是字节数；块名要按"语言高低位调过来＋代码页同样调过来"排成 8 位十六进制。
    tr = query_bytes(BS.join(("VarFileInfo", "Translation")))
    if not tr or len(tr) % 4:
        return None
    for i in range(0, len(tr), 4):
        b = tr[i:i + 4]
        block = f"{b[1]:02x}{b[0]:02x}{b[3]:02x}{b[2]:02x}"
        got = query_w(BS.join(("StringFileInfo", block, "FileDescription")))
        if got:
            return got
    return None


def probe_launcher(exe: str, arg: str = "D:" + BS + "某 一片.mkv",
                   env: dict[str, str] | None = None) -> tuple[str | None, str]:
    """用启动器自己的探针档核命令行：不起 GUI、不开文件，只读它算出来的那一串。
    文件名**故意带空格**——没加引号的话它会变成两个参数，这是这条链上最容易错的一处。"""
    out = os.path.join(tempfile.mkdtemp(prefix="luhui-probe-"), "cmdline.txt")
    run_env = dict(os.environ, GELU_LAUNCHER_PROBE=out, **(env or {}))
    proc = subprocess.run([exe, arg], env=run_env, capture_output=True, timeout=30)
    if not os.path.exists(out):
        return None, f"rc={proc.returncode} 探针档没写文件（stderr={proc.stderr[:120]!r}）"
    return open(out, encoding="utf-8", errors="replace").read().strip(), f"rc={proc.returncode}"


def build_launcher(rebuild: bool = True) -> list[str]:
    """生成 .cs（变了才重写）＋编 exe＋核三件事：FileDescription、探针档拼出的命令行形状、
    exe 里**烤进去**的解释器与入口脚本是不是当前这台机器的。

    `rebuild=False` 是给 `--check` 用的：只核对盘上那份，不写文件也不动 csc。烤进去的路径
    那条为什么要在意：注册表里写的是 exe，exe 里的 pythonw／open_file.py 路径才是真正干活的那条；
    项目搬过家之后 .reg 会重生成、exe 却可能还是旧的，于是"注册成功但点了没反应"。
    """
    problems: list[str] = []
    text = launcher_cs()
    problems += [f"launcher.cs：{p}" for p in lint_cs(text)]
    if problems:
        return problems
    disk = open(LAUNCH_CS, encoding="ascii", errors="replace").read() if os.path.exists(LAUNCH_CS) else ""
    changed = disk != text
    if rebuild and changed:
        write_text(LAUNCH_CS, text, "ascii")
    stale = os.path.exists(LAUNCH_EXE) and (
        not os.path.exists(LAUNCH_CS)
        or os.path.getmtime(LAUNCH_EXE) < os.path.getmtime(LAUNCH_CS)
        or os.path.getmtime(LAUNCH_EXE) < os.path.getmtime(__file__))
    if not os.path.exists(LAUNCH_EXE):
        if not rebuild:
            return [f"盘上没有 {LAUNCH_EXE}（--check 不编译）：先不带参数跑一次生成"]
        stale = True
    if rebuild and (changed or stale):
        if not os.path.exists(CSC):
            return [f"编译不了：这台机器上没有 {CSC}"]
        args = [CSC, "-nologo", "-target:winexe", "-platform:anycpu",
                "-out:" + LAUNCH_EXE]
        if os.path.exists(ICON):
            args.append("-win32icon:" + ICON)
        args.append(LAUNCH_CS)
        proc = subprocess.run(args, capture_output=True, timeout=300)
        if proc.returncode != 0:
            return [f"csc 编译失败 rc={proc.returncode}："
                    f"{(proc.stdout + proc.stderr).decode('gbk', errors='replace')[:300]}"]
        built = True
    else:
        built = False
    if rebuild and not changed and stale:
        # exe 比 .cs／本脚本旧，但 .cs 内容没变 ⇒ 沿用没问题，下面"烤进去的路径"那条判据兜住真风险
        pass
    if not rebuild and changed:
        problems.append("盘上那份 launcher.cs 与本次要生成的不一致（解释器或路径变了）："
                        "重跑一次 python packaging" + BS + "make_launchers.py 重新编译")
    got = file_description(LAUNCH_EXE)
    if got != APP_TITLE:
        problems.append(f"启动器的 FileDescription 是 {got!r}，不是 {APP_TITLE!r}"
                        "——「打开方式」列表里显示的就是这一串，等于白注册")
    # 形状：环境变量能覆盖，说明这条命令是**拼**出来的，参数会原样带下去、且加了引号
    cmd, note = probe_launcher(LAUNCH_EXE, env={"GELU_PYTHONW": "C:" + BS + "py.exe",
                                                "GELU_ENTRY": "C:" + BS + "no dir" + BS + "entry.py"})
    if cmd is None:
        problems.append(f"启动器探针档不工作（{note}）：这条命令行的形状没法核对")
    else:
        for want in ("C:" + BS + "py.exe", "C:" + BS + "no dir" + BS + "entry.py",
                     '"' + "D:" + BS + "某 一片.mkv" + '"'):
            if want not in cmd:
                problems.append(f"探针档命令行里没有 {want!r}：实测 {cmd[:120]!r}")
    # 真值：不带覆盖跑一遍，看 exe 里烤进去的是不是当前这台机器的解释器与入口
    baked, note2 = probe_launcher(LAUNCH_EXE, arg="D:" + BS + "某一片.mkv")
    if baked is None:
        problems.append(f"启动器探针档（不带覆盖）不工作（{note2}）")
    else:
        for want in (interpreter(), OPEN_PY):
            if want not in baked:
                problems.append(f"exe 里烤进去的命令行没有 {want}：这台机器换过路径，实测 {baked[:120]!r}")
    print(f"      （启动器{'重新编译' if built else '沿用盘上那份'}；FileDescription={got!r}；"
          f"探针档 {note}／{note2}）")
    return problems


def reg_openwith(exts: list[str] | None = None, exe: str | None = None,
                 take: str = "%1", icon: str | None = None,
                 progid: str | None = None) -> str:
    """让播放器进「打开方式」列表的那份 .reg：三根自己的键 ＋ 每个扩展名一条 OpenWithProgids。

    每个扩展名**只往 OpenWithProgids 里加一条值**：那是"这个类型还能用谁打开"的清单，
    不是"默认用谁打开"——后者住在 UserChoice（有哈希保护）和扩展名键的默认值里，两处都不碰。
    """
    exts = exts if exts is not None else media_exts()
    pid = progid or PROGID
    target = exe or LAUNCH_EXE
    cmd = f'"{target}"' + (f' "{take}"' if take else "")
    ic = icon if icon is not None else ICON
    out = HEAD + "\r\n\r\n"
    pfx = HKCU + BS + "Software" + BS + "Classes"
    out += f"[{pfx}{BS}{pid}]\r\n"
    out += f'@="{_reg_escape(pid)}"\r\n'
    out += f'"FriendlyTypeName"="{_reg_escape(APP_TITLE)}"\r\n'
    out += f'"ApplicationDescription"="{_reg_escape("本地视频播放器（libmpv 内核）")}"\r\n'
    out += "\r\n"
    if ic and os.path.exists(ic):
        out += f"[{pfx}{BS}{pid}{BS}DefaultIcon]\r\n"
        out += f'@="{_reg_escape(ic)},0"\r\n\r\n'
    out += f"[{pfx}{BS}{pid}{BS}shell{BS}open{BS}command]\r\n"
    out += f'@="{_reg_escape(cmd)}"\r\n\r\n'
    out += f"[{HKCU}{BS + KEY_APP}]\r\n"
    out += f'"FriendlyAppName"="{_reg_escape(APP_TITLE)}"\r\n\r\n'
    if ic and os.path.exists(ic):
        out += f"[{HKCU}{BS + KEY_APP}{BS}DefaultIcon]\r\n"
        out += f'@="{_reg_escape(ic)},0"\r\n\r\n'
    out += f"[{HKCU}{BS + KEY_APP}{BS}shell{BS}open{BS}command]\r\n"
    out += f'@="{_reg_escape(cmd)}"\r\n\r\n'
    out += f"[{HKCU}{BS + KEY_APPPATHS}]\r\n"
    out += f'@="{_reg_escape(target)}"\r\n'
    out += f'"Path"="{_reg_escape(ROOT)}"\r\n\r\n'
    for ext in exts:
        out += f"[{pfx}{BS}{ext}{BS}OpenWithProgids]\r\n"
        out += f'"{pid}"=""\r\n\r\n'
    return out


def reg_openwith_del(exts: list[str] | None = None, progid: str | None = None) -> str:
    """撤销：删自己那三根键，并把每个扩展名里**我们那一条值**摘掉（`"X"=-`）。

    绝不用 `[-…\\Classes\\.mp4]` 那种写法：那会把用户在这根键里已有的东西（这台机器上
    .mp4 的默认值就是迅雷影音写的）一起删掉——撤销件只许撤自己添的。
    """
    exts = exts if exts is not None else media_exts()
    pid = progid or PROGID
    out = HEAD + "\r\n\r\n"
    for key in (KEY_PROGID, KEY_APP, KEY_APPPATHS):
        out += f"[-{HKCU}{BS + key}]\r\n"
    out += "\r\n"
    pfx = HKCU + BS + "Software" + BS + "Classes"
    for ext in exts:
        out += f"[{pfx}{BS}{ext}{BS}OpenWithProgids]\r\n"
        out += f'"{pid}"=-\r\n\r\n'
    return out


def reg_add(exe: str | None = None, entry: str | None = None,
            take: str = "%1", with_icon: bool = True) -> str:
    """一份"加右键菜单"的 .reg 正文。参数化是为了让证伪样本走**同一个转义通道**——
    自测里拿未转义的字面量去 replace 已转义的正文，替换会静默落空，四条坏样本全变"干净"，
    那就是恒真的判据（这条是被 selftest 自己抓出来的）。
    """
    cmd = f'"{exe or interpreter()}" "{entry or OPEN_PY}"'
    if take:
        cmd += f' "{take}"'
    out = HEAD + "\r\n\r\n"
    out += f"[{HKCU}\\{SHELL_KEY}]\r\n"
    out += f'@="{_reg_escape("用LuHui播放器播放")}"\r\n'
    if with_icon and os.path.exists(ICON):
        out += f'"Icon"="{_reg_escape(ICON)}"\r\n'
    out += "\r\n" + f"[{HKCU}\\{SHELL_KEY}\\command]\r\n"
    out += f'@="{_reg_escape(cmd)}"\r\n'
    return out


def reg_del() -> str:
    # 键名前面挂 "-" 就是"删掉这个键连同子键"，regedit 认这个写法。
    return HEAD + "\r\n\r\n" + f"[-{HKCU}\\{SHELL_KEY}]\r\n"


# ---------------------------------------------------------------- 复查（纯函数）
PLACEHOLDERS = ("@ROOT@", "@PY@", "@OPEN@", "{{", "}}")


def _lines(body: str) -> list[str]:
    """按行拆（CRLF/LF 都认）：结构检查要跑在"行"上，坏行尾另由一条判据点名。"""
    return body.replace("\r\n", "\n").split("\n")


def _reg_unescape(seg: str) -> str:
    """.reg 的两个转义：`\\\\`＝一个反斜杠，`\\"`＝一个引号。"""
    return seg.replace("\\\\", "\x01").replace('\\"', '"').replace("\x01", "\\")


def _single_backslash_run(seg: str) -> bool:
    """扫"落单的、又不在转义对里的反斜杠"——合法 .reg 值里每个反斜杠都成对或引着引号。"""
    i = 0
    while i < len(seg):
        if seg[i] == "\\":
            nxt = seg[i + 1:i + 2]
            if nxt in ("\\", '"'):
                i += 2
                continue
            return True
        i += 1
    return False


def command_value(body: str) -> str:
    """取 `…\\command]` 那节里的默认值（已反转义）。没有就回空串。"""
    inside = False
    for line in _lines(body):
        s = line.strip()
        if s.startswith("["):
            inside = s[1:].rstrip("]").endswith("\\command")
            continue
        if inside and s.startswith('@="') and s.endswith('"'):
            return _reg_unescape(s[3:-1])
    return ""


def lint_reg(body: str) -> list[str]:
    problems: list[str] = []
    if "\ufeff" in body:
        problems.append("正文里有 BOM 字符（它该是文件头两个字节，不该出现在文本里）")
    if not body.startswith(HEAD):
        problems.append("缺第一行版本头：regedit 会直接判这份文件无效")
    if body.replace("\r\n", "").find("\n") >= 0:
        problems.append("混进裸 LF：.reg 要整份 CRLF")
    lines = _lines(body)
    keys = [l.strip() for l in lines if l.strip().startswith("[")]
    if not keys:
        problems.append("一个键都没有")
    for k in keys:
        top = k[1:-1].lstrip("-") if k.endswith("]") else k.lstrip("-")
        if "LOCAL_MACHINE" in top.upper():
            problems.append(f"碰了 HKLM（要管理员权限，且不该由脚本代劳）：{top}")
        if not top.startswith(HKCU):
            problems.append(f"根不是 {HKCU}：{top}")
    for tok in PLACEHOLDERS:
        if tok in body:
            problems.append(f"记号没替换掉：{tok}")
    for line in lines:
        s = line.strip()
        if not s or s.startswith("[") or "=" not in s:
            continue
        val = s.split("=", 1)[1].strip()
        if not val.startswith('"'):
            continue        # DWORD 之类这份模板里用不到
        end = val.rfind('"')
        seg = val[1:end] if end > 0 else val[1:]
        if _single_backslash_run(seg):
            problems.append(f"反斜杠没双写：{s[:64]}")
    return problems


def lint_command_line(body: str, path_exists=None) -> list[str]:
    """command 值专查：取参写法、解释器与入口脚本存不存在。"""
    if path_exists is None:
        path_exists = os.path.exists
    cmd = command_value(body)
    if not cmd:
        return []           # 撤销模板没有 command 节，缺 %1 不算它的错
    problems: list[str] = []
    if "%~1" in cmd:
        problems.append("命令里写了 %~1（那是批处理的取参语法）：注册表要用 %1")
    if "%1" not in cmd:
        problems.append("命令里没有 %1：右键选了文件也不知道要打开哪一个")
    for tok in cmd.split('"'):
        if tok.lower().endswith((".exe", ".py")) and not path_exists(tok):
            problems.append(f"命令指向的文件不存在：{tok}")
    return problems


def _reg_sections(body: str) -> list[tuple[str, bool, list[str]]]:
    """把 .reg 正文拆成 (键路径, 是否删除键, 该节下的值行) —— 转义只发生在**值**里，
    键路径按单反斜杠看，所以这里对键名不做反转义。"""
    out: list[list] = []
    cur = None
    for line in _lines(body):
        s = line.strip()
        if not s:
            continue
        if s.startswith("["):
            raw = s[1:].rstrip("]")
            dele = raw.startswith("-")
            cur = [raw[1:] if dele else raw, dele, []]
            out.append(cur)
        elif cur is not None:
            cur[2].append(s)
    return [(k, d, v) for k, d, v in out]


def _cmd_first_token(cmd: str) -> str:
    """命令行里第一个带引号的可执行文件；没引号就退回第一个空格前的串。"""
    if cmd.startswith('"'):
        end = cmd.find('"', 1)
        return cmd[1:end] if end > 0 else cmd[1:]
    return cmd.split(" ")[0]


def lint_openwith(body: str, exts: list[str] | None = None, path_exists=None,
                  progid: str | None = None, exe: str | None = None,
                  title: str | None = None) -> list[str]:
    """「打开方式」那套注册的专用闸门。它管三件**只有右键菜单那条判据管不到**的事：
    ① 不许碰默认程序（`UserChoice`／扩展名键的默认值）；② 扩展名名单必须等于 `MEDIA_EXTS`
    现取的那份（名单落后＝新格式在列表里根本没有我们，而注册表里落后是看不见的）；
    ③ 落点必须是真启动器 exe——写成 pythonw 的话列表里显示"pythonw"，等于没注册。
    """
    exts = exts if exts is not None else media_exts()
    pid = progid or PROGID
    target = exe or LAUNCH_EXE
    name = title or APP_TITLE
    if path_exists is None:
        path_exists = os.path.exists
    problems = lint_reg(body)
    sections = _reg_sections(body)
    keys = [k for k, _d, _v in sections]

    if "userchoice" in body.lower():
        problems.append("碰了 UserChoice：那是默认程序，Win10/11 有哈希保护，硬写不可靠也不该做")

    want = {k.lower() for k in (HKCU + BS + KEY_PROGID, HKCU + BS + KEY_APP,
                                HKCU + BS + KEY_APPPATHS)}
    got = {k.lower() for k in keys}
    for miss in sorted(want - got):
        problems.append(f"少了这一根键，列表里就不会有我们：{miss}")

    ow: dict[str, list[str]] = {}
    pfx_cls = ("software" + BS + "classes" + BS).lower()
    for key, dele, vals in sections:
        parts = key.split(BS)
        low = key.lower()
        if dele:
            continue
        if parts[-1].lower() == "openwithprogids" and len(parts) >= 5 \
                and parts[-3].lower() == "classes":
            ow.setdefault(parts[-2].lower(), []).extend(vals)
            continue
        if low.startswith((HKCU + BS).lower() + pfx_cls) and parts[-1].startswith(".") \
                and len(parts) == 4:
            for v in vals:
                if v.startswith("@="):
                    problems.append(f"往扩展名键 {parts[-1]} 的默认值里写了东西：那就是改默认打开方式")

    missing = sorted({e.lower() for e in exts} - set(ow))
    extra = sorted(set(ow) - {e.lower() for e in exts})
    if missing:
        problems.append(f"有 {len(missing)} 个扩展名没进 OpenWithProgids（名单落后于 MEDIA_EXTS？）："
                        + "、".join(missing[:3]) + ("…" if len(missing) > 3 else ""))
    if extra:
        problems.append("注册了 MEDIA_EXTS 之外的扩展名（播放器打不开的类型）：" + "、".join(extra[:3]))
    for ext, vals in sorted(ow.items()):
        for v in vals:
            head = v.split("=", 1)[0].strip()
            if head.lower() == '"@'.lower():
                problems.append(f"{ext} 的 OpenWithProgids 里写了默认值：改的会是默认程序")
                continue
            if head != f'"{pid}"':
                problems.append(f"{ext} 的 OpenWithProgids 里那条值不叫 {pid}：{v[:48]}"
                                "（撤销件按名字摘值，名字对不上就摘不掉）")
            elif not v.endswith('=""'):
                problems.append(f"{ext} 的 OpenWithProgids 值不是空串：{v[:48]}"
                                "（那条惯例是空 REG_SZ，写内容会让 Explorer 显示成别的名字）")

    cmds = [(k, v) for k, _d, vv in sections for v in vv if k.lower().endswith(BS + "command")]
    if len(cmds) < 2:
        problems.append(f"shell\\open\\command 只 {len(cmds)} 处：ProgID 与 Applications 两处都要有，"
                        "少一处就是列表里有名字、点了却没反应")
    for key, v in cmds:
        cmd = _reg_unescape(v.split("=", 1)[1].strip()[1:-1]) if "=" in v else ""
        if "%~1" in cmd:
            problems.append(f"{key} 的命令里写了 %~1（批处理语法）：注册表要用 %1")
        if "%1" not in cmd:
            problems.append(f"{key} 的命令里没有 %1：选了文件也不知道打开哪一个")
        first = _cmd_first_token(cmd)
        if first.lower() != target.lower():
            problems.append(f"{key} 的命令落点是 {os.path.basename(first) or first!r}，不是 "
                            f"{LAUNCH_NAME}：列表里显示的是那个 exe 的文件描述，"
                            "写 pythonw 就会出现\"pythonw\"这种认不出的名字")
        if first and not path_exists(first):
            problems.append(f"{key} 指向的文件不存在：{first}")
    if target.lower().endswith("pythonw.exe"):
        problems.append("落点给了 pythonw.exe：它会把手上的 .mkv 当脚本执行，既不播也显示成 pythonw")
    def value_of(vals: list[str], name: str) -> str:
        """取某节里名为 `name` 的值（`@`＝默认值），已反转义；没有就回空串。"""
        for v in vals:
            head, sep, rest = v.partition("=")
            if not sep:
                continue
            if head.strip().lower() == name.lower():
                rest = rest.strip()
                return _reg_unescape(rest[1:-1]) if rest.startswith('"') else ""
        return ""

    for key, _d, vals in sections:
        low = key.lower()
        if low == (HKCU + BS + KEY_APPPATHS).lower():
            got2 = value_of(vals, "@")
            if got2.lower() != target.lower():
                problems.append(f"App Paths 的默认值是 {got2!r}，不是启动器："
                                "Explorer 按这根键定位 exe，写错了就等于没注册")
            if not value_of(vals, '"Path"'):
                problems.append("App Paths 少了 Path 值：它的惯例是填 exe 所在目录，缺了会少走一条查找路")
        if low == (HKCU + BS + KEY_APP).lower():
            friendly = value_of(vals, '"FriendlyAppName"')
            if friendly != name:
                problems.append(f"Applications 的 FriendlyAppName 是 {friendly!r}，不是 {name!r}："
                                "列表里那行名字有一多半靠它")
    return problems


def lint_openwith_del(body: str, exts: list[str] | None = None,
                      progid: str | None = None) -> list[str]:
    """撤销件单独验：它比新增件更容易出事——一行写错删的就是别人的注册。
    三条硬规矩：只删自己那三根键、每个扩展名只按**名字**摘一条值、
    绝不用 `[-…\\Classes\\.mp4]` 或 `[-…\\OpenWithProgids]` 整根删（那会连别人的条目一起没）。
    """
    exts = exts if exts is not None else media_exts()
    pid = progid or PROGID
    problems = lint_reg(body)
    if "userchoice" in body.lower():
        problems.append("撤销件里出现了 UserChoice：撤销只许撤自己添的")
    sections = _reg_sections(body)
    deleted = {k.lower() for k, d, _v in sections if d}
    for key, dele, vals in sections:
        parts = key.split(BS)
        last = parts[-1].lower()
        if dele and (last == "openwithprogids" or (last.startswith(".") and len(parts) == 4)):
            problems.append(f"整根删掉了 {key}：那里面可能有别的播放器添的条目，撤销只许摘自己那一条值")
    for want in (HKCU + BS + KEY_PROGID, HKCU + BS + KEY_APP, HKCU + BS + KEY_APPPATHS):
        if want.lower() not in deleted:
            problems.append(f"没有删这一根自己添的键：{want}")
    ow: dict[str, list[str]] = {}
    for key, dele, vals in sections:
        parts = key.split(BS)
        if parts[-1].lower() == "openwithprogids" and len(parts) >= 5:
            ow.setdefault(parts[-2].lower(), []).extend(vals)
    missing = sorted({e.lower() for e in exts} - set(ow))
    if missing:
        problems.append(f"{len(missing)} 个扩展名没被摘值（撤销后列表里会留幽灵条目）："
                        + "、".join(missing[:3]) + ("…" if len(missing) > 3 else ""))
    for ext, vals in sorted(ow.items()):
        for v in vals:
            if v.strip() != f'"{pid}"=-':
                problems.append(f"{ext} 的摘除行不是一条按名字的删除：{v[:48]}")
    return problems


def lint_bat(text: str, path_exists=None) -> list[str]:
    if path_exists is None:
        path_exists = os.path.exists
    problems = []
    if not text.startswith("@echo off"):
        problems.append("少了 @echo off：双击会把每条命令先打一遍")
    # 这一条是被**真跑**抓出来的，不是想出来的：LF-only 的 .bat 里凡是带中文的行都会被
    # cmd 从中间劈开，后半截当成命令执行（实测报 "'遍故障自检并停住给人看。' 不是内部或外部
    # 命令"＋"系统找不到指定的路径"，而 `python -m app.doctor` 那一行根本没跑到）。
    if "\n" in text.replace("\r\n", ""):
        problems.append("混进裸 LF：cmd 读 LF-only 批处理会把带中文的行从中间劈开，必须整份 CRLF")
    if not text.endswith("\r\n"):
        problems.append("最后一行没有 CRLF 收尾：cmd 可能漏执行末行（pause 漏掉＝双击后窗口一闪就没）")
    if 'cd /d "%~dp0"' not in text:
        problems.append("没先 cd 到脚本所在目录：-m app.main 会找不到包")
    if "%*" not in text and "-m app.doctor" not in text:
        problems.append("既没透传参数也没写死要跑的命令")
    for line in text.splitlines():
        if line.strip().startswith("@") and "echo off" not in line:
            problems.append(f"以 @ 开头的行会被当成命令执行：{line[:40]}")
        for seg in line.split('"'):
            if seg.lower().endswith(".exe") and not path_exists(seg):
                problems.append(f"写死的解释器不存在：{seg}")
    try:
        text.encode("gbk")
    except UnicodeEncodeError as exc:
        problems.append(f"有 GBK 存不下的字符（.bat 按 GBK 落盘）：{exc}")
    return problems


def lint_open_py(text: str) -> list[str]:
    problems = []
    if "sys.path.insert" not in text:
        problems.append("没把项目根塞进 sys.path：注册表那条命令没有工作目录，import app 会炸")
    if "main(sys.argv[1:])" not in text:
        problems.append("没把参数转交给 app.main：右键选中文件后打不开那一个")
    if "__file__" not in text:
        problems.append("根目录不是从 __file__ 推的：换个调用目录就会算错")
    # ROOT 必须从 __file__ 往上跳**两层**（packaging\ 的父目录才是项目根）。上一版只 grep
    # "__file__ 在不在"，于是写成 `dirname(abspath(__file__))` 这种"只跳一层、算出
    # packaging\"的根也照样放行——判据太松，真跑到"陌生 cwd"那条才翻红。
    root_line = next((l for l in text.splitlines() if l.startswith("ROOT")), "")
    if not root_line:
        problems.append("没有 ROOT = 这一行：不知道往 sys.path 里插的是哪个目录")
    elif "__file__" not in root_line or root_line.count("dirname(") < 2:
        problems.append(f"ROOT 没从 __file__ 往上跳两层（这行里 dirname( 只有 "
                        f"{root_line.count('dirname(')} 次）：算出来的是 packaging\\ 不是项目根")
    try:
        compile(text, "open_file.py", "exec")
    except SyntaxError as exc:
        problems.append(f"语法就不对：{exc}")
    return problems


def lint_del(body: str) -> list[str]:
    """撤销模板单独验形状：必须是一根带 "-" 前缀的键，且不许带值。"""
    problems = lint_reg(body)
    keys = [l for l in body.split("\r\n") if l.startswith("[")]
    if len(keys) != 1:
        problems.append(f"撤销模板应该只有一根键，这里 {len(keys)} 根")
    elif not keys[0][1:].startswith("-"):
        problems.append("键名前面没有 '-'：这份文件是新增而不是删除")
    if "=" in body.replace(HEAD, ""):
        problems.append("删除键的模板里不该有值行")
    return problems


# ---------------------------------------------------------------- 落盘与回读
def to_crlf(text: str) -> str:
    """把源码里的 LF 模板归一成 CRLF——**判据跑在归一之后的正文上**，这样"内存里那份"
    和「盘上那份」是同一串字节，不会出现 lint 放行、cmd 却把行劈开的两套真相。"""
    return text.replace("\r\n", "\n").replace("\n", "\r\n")


def write_reg(path: str, body: str) -> None:
    """regedit 认 UTF-16LE + BOM；本项目路径含中文，ANSI 会当场变问号。"""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as fh:
        fh.write(b"\xff\xfe")
        fh.write(body.encode("utf-16-le"))
        fh.flush()
        os.fsync(fh.fileno())


def write_text(path: str, text: str, encoding: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding=encoding, newline="") as fh:
        fh.write(text)
        fh.flush()
        os.fsync(fh.fileno())


def read_reg(path: str) -> str:
    """回读 .reg：核对 BOM 再跳过头两字节解码——复查的对象是**盘上那一份**。"""
    with open(path, "rb") as fh:
        raw = fh.read()
    if raw[:2] != b"\xff\xfe":
        return ""
    return raw[2:].decode("utf-16-le")


def read_text(path: str, encoding: str) -> str:
    # newline="" 是必需的：默认的通用换行会把盘上的 CRLF 读成 LF，于是"行尾"这条判据
    # 永远在罚好产物、也永远抓不到真坏了行尾的产物（这一版就是这么自缚的）。
    with open(path, encoding=encoding, errors="strict", newline="") as fh:
        return fh.read()


